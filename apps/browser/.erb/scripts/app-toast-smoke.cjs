const { app, BrowserWindow, WebContentsView } = require('electron');
const fs = require('fs'); const os = require('os'); const path = require('path'); const assert = require('assert');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'kudium-toast-'));
app.setPath('userData', temporary);
require('esbuild').buildSync({entryPoints:['src/main/appToast.ts'],bundle:true,platform:'node',external:['electron'],outfile:path.join(temporary,'toast.cjs')});
const {showAppToast} = require(path.join(temporary,'toast.cjs'));
const wait = ms => new Promise(resolve => setTimeout(resolve,ms));
app.whenReady().then(async()=>{
  const owner = new BrowserWindow({show:true,width:800,height:600});
  const page = new WebContentsView(); owner.contentView.addChildView(page);page.setBounds({x:0,y:40,width:800,height:560});
  await page.webContents.loadURL('data:text/html,<input value="unsaved draft">');
  const before = page.getBounds();
  let acknowledgements=0;
  try {
    await showAppToast(owner,{id:'battery',title:'Low battery',message:'Battery is at 20%. Connect your charger to keep browsing.',tone:'warning',durationMs:120000,onDismiss:()=>{acknowledgements++}});
    const toast = owner.getChildWindows()[0]; assert(toast && toast.isVisible());
    assert.equal(await toast.webContents.executeJavaScript("getComputedStyle(document.querySelector('.remaining')).animationDuration"),'60s','Custom duration is capped at sixty seconds');
    assert.equal(await toast.webContents.executeJavaScript("getComputedStyle(document.querySelector('.countdown')).pointerEvents"),'none','Ring does not block dismiss');
    const closeDesign=await toast.webContents.executeJavaScript(`(()=>{const card=document.getElementById('toast').getBoundingClientRect(),close=document.querySelector('.dismiss').getBoundingClientRect();return{overlap:close.top<card.top&&close.bottom>card.top,inside:close.top>=0&&close.right<=innerWidth,weight:document.querySelector('.close-mark').getAttribute('stroke-width')}})()`);
    assert(closeDesign.overlap&&closeDesign.inside,'Close overlaps top corner without clipping');
    assert.equal(closeDesign.weight,'2','Close mark is bolder');
    assert.deepStrictEqual(page.getBounds(),before,'No page layout change');
    assert.equal(await page.webContents.executeJavaScript('document.querySelector("input").value'),'unsaved draft');
    const state = await toast.webContents.executeJavaScript(`({title:document.getElementById('title').textContent,message:document.getElementById('message').textContent,scroll:document.documentElement.scrollHeight>innerHeight})`);
    assert.equal(state.title,'Low battery'); assert.equal(state.scroll,false);
    const material = await toast.webContents.executeJavaScript(`(() => {
      const style = getComputedStyle(document.getElementById('toast'));
      return {glass:document.body.classList.contains('glass'),background:style.backgroundColor,blur:style.backdropFilter};
    })()`);
    if (material.glass) {
      const alpha=Number(material.background.match(/,\s*([\d.]+)\)$/)?.[1]);
      assert(alpha>0&&alpha<=0.1,'Native glass tint stays below ten percent opacity: '+material.background);
      assert.equal(material.blur,'none','No redundant CSS blur over native material');
      toast.webContents.debugger.attach('1.3');
      await toast.webContents.debugger.sendCommand('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-transparency',value:'reduce'}]});
      const accessible=await toast.webContents.executeJavaScript("getComputedStyle(document.getElementById('toast')).backgroundColor");
      assert(!accessible.startsWith('rgba'),'Reduced transparency restores opaque surface');
      toast.webContents.debugger.detach();
    }
    const parentBounds=owner.getContentBounds(),bounds=toast.getBounds();
    assert.equal(bounds.x+bounds.width,parentBounds.x+parentBounds.width-32,'Top right placement clears frame and scrollbar');
    const button = await toast.webContents.executeJavaScript(`(()=>{const r=document.querySelector('.dismiss').getBoundingClientRect();return{x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`);
    toast.webContents.sendInputEvent({type:'mouseDown',...button,button:'left',clickCount:1});
    toast.webContents.sendInputEvent({type:'mouseUp',...button,button:'left',clickCount:1});
    await wait(150);assert(toast.isDestroyed(),'Dismiss button closes overlay');
    assert.equal(acknowledgements,1,'Explicit close acknowledges once');
    await showAppToast(owner,{id:'generic',title:'Saved',message:'<script>unsafe</script>',tone:'success',durationMs:150,onDismiss:()=>{acknowledgements++}});
    const next=owner.getChildWindows()[0];
    assert.equal(await next.webContents.executeJavaScript('document.getElementById("message").textContent'),'<script>unsafe</script>','Message is text');
    await wait(250);assert(next.isDestroyed(),'Automatic expiry');
    assert.equal(acknowledgements,1,'Expiry does not acknowledge');
    let actions = 0;
    await showAppToast(owner,{id:'action',title:'Low battery',message:'20% remaining.',action:{label:'Save energy',run:async()=>{actions++}}});
    const actionable=owner.getChildWindows()[0];
    assert.equal(await actionable.webContents.executeJavaScript("getComputedStyle(document.querySelector('.remaining')).animationDuration"),'10s','Action toast gets ten seconds');
    const actionPoint=await actionable.webContents.executeJavaScript(`(()=>{const r=document.querySelector('.action').getBoundingClientRect();return{x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`);
    actionable.webContents.sendInputEvent({type:'mouseDown',...actionPoint,button:'left',clickCount:1});
    actionable.webContents.sendInputEvent({type:'mouseUp',...actionPoint,button:'left',clickCount:1});
    await wait(150);
    assert.equal(actions,1,'Action runs exactly once');
    assert(actionable.isDestroyed(),'Action dismisses toast');
    const moveListeners = owner.listenerCount('move');
    for (let index=0;index<5;index++) await showAppToast(owner,{id:'stack-'+index,title:'Notice '+index,message:'Stacked message',durationMs:1000,onDismiss:()=>{acknowledgements++}});
    const stack=owner.getChildWindows().sort((a,b)=>a.getBounds().y-b.getBounds().y);
    assert.equal(stack.length,5,'All notifications retained');
    assert.equal(stack.filter(item=>item.isVisible()).length,3,'Only three visible');
    assert.equal(owner.listenerCount('move'),moveListeners+1,'Stack shares owner listeners');
    for(let index=1;index<3;index++) assert(stack[index].getBounds().y>=stack[index-1].getBounds().y+stack[index-1].getBounds().height+8,'No overlap: '+JSON.stringify(stack.map(item=>item.getBounds())));
    assert.equal(await stack[0].webContents.executeJavaScript("document.querySelector('.dismiss-all').hidden"),false,'Dismiss all shown');
    await wait(1150);
    assert(stack.slice(0,3).every(item=>item.isDestroyed()),'Visible countdowns expire independently');
    assert(stack.slice(3).every(item=>!item.isDestroyed()&&item.isVisible()),'Queue becomes visible without expiring early');
    await stack[3].webContents.executeJavaScript("document.querySelector('.dismiss-all').click()");
    await wait(100);
    assert(stack.every(item=>item.isDestroyed()),'Dismiss all clears stack');
    assert.equal(acknowledgements,3,'Dismiss all acknowledges both remaining toasts');
    assert.equal(owner.listenerCount('move'),moveListeners,'Listeners cleaned up');
    await showAppToast(owner,{id:'same',title:'First',message:'First',durationMs:5000});
    const replaced=owner.getChildWindows()[0];
    await showAppToast(owner,{id:'same',title:'Updated',message:'Updated',durationMs:5000});
    assert(replaced.isDestroyed(),'Matching ID updates instead of duplicating');
    assert.equal(owner.getChildWindows().length,1);
    for(let index=0;index<4;index++) await showAppToast(owner,{id:'clear-'+index,title:'Clear',message:'Clear',durationMs:5000});
    const pending=owner.getChildWindows();
    await pending[0].webContents.executeJavaScript("document.querySelector('.dismiss-all').click()");
    await wait(100);
    assert(pending.every(item=>item.isDestroyed()),'Dismiss all clears queued notifications too');
    console.log('PASS native toast: top right, retained webpage/draft, safe message text, real dismiss click, automatic expiry.');
  } finally {owner.destroy();}
}).then(()=>app.quit()).catch(error=>{console.error(error);app.exit(1)});
app.on('will-quit',()=>fs.rmSync(temporary,{recursive:true,force:true}));
