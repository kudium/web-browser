/* eslint-disable no-await-in-loop, no-restricted-syntax */
const {app, BrowserWindow, WebContentsView} = require('electron');
const fs = require('fs');
const os = require('os');
const path = require('path');
const http = require('http');
const assert = require('assert');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'touchbox-developer-'));
app.setPath('userData', path.join(root, 'profile'));
// Bundle both modules together so their durable-settings cache is shared.
fs.writeFileSync(path.join(root,'entry.ts'), `export * from ${JSON.stringify(path.resolve('src/main/siteDeveloper'))}; export * from ${JSON.stringify(path.resolve('src/main/siteSettings'))};`);
require('esbuild').buildSync({entryPoints:[path.join(root,'entry.ts')], bundle:true, platform:'node', external:['electron'], outfile:path.join(root,'entry.cjs')});
const api = require(path.join(root,'entry.cjs'));
const wait = ms => new Promise(resolve=>setTimeout(resolve,ms));
async function until(test) { for(let i=0;i<100;i++){if(test())return;await wait(50);}throw new Error('Timed out'); }
const server = http.createServer((req,res)=>{res.setHeader('Content-Type','text/html');res.setHeader('Content-Security-Policy', "default-src 'self'; script-src 'unsafe-inline'; style-src 'self'");res.end(`<!doctype html><title>Developer fixture</title><script>document.dispatchEvent(new Event('touchbox-probe'));document.documentElement.dataset.beforeObserved=document.documentElement.dataset.before || 'missing';</script><h1>Fixture content</h1>${req.url==='/iframe'?'':'<iframe src="/iframe"></iframe>'}`);});
app.whenReady().then(async()=>{
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const origin=`http://127.0.0.1:${server.address().port}`;
  const w=new BrowserWindow({show:false});
  const view=new WebContentsView({webPreferences:{preload:api.siteDeveloperPreload(),sandbox:true,contextIsolation:true,nodeIntegration:false,partition:'persist:developer-fixture'}});
  w.contentView.addChildView(view);
  const c=view.webContents;
  c.on('preload-error',(_,file,error)=>console.error('preload',file,error));
  api.registerDeveloperPage(c,'work',()=>{});
  const config={enabled:true,before:"log('before', document.readyState, typeof require); document.addEventListener('touchbox-probe', () => {document.documentElement.dataset.before='yes'});",after:"await Promise.resolve(); log('after', url, content.includes('Fixture content')); log('title', document.title);",css:'h1 { color: rgb(12, 34, 56); }'};
  api.updateSiteSettings('work',origin,{developer:config});
  await c.loadURL(origin+'/page');
  await until(()=>api.developerState(c,origin).status==='success').catch(error=>{console.log(api.developerState(c,origin));throw error});
  let state=api.developerState(c,origin);
  assert(state.logs.some(l=>l.message==='before loading undefined'),'before runs before website scripts, without require');
  assert(state.logs.some(l=>l.message.includes('after '+origin+'/page true')),'after gets URL and HTML');
  assert.equal(state.logs.filter(l=>l.message.startsWith('before ')).length,1,'main frame only');
  assert.equal(await c.executeJavaScript('document.documentElement.dataset.beforeObserved'),'yes','website script observes before-load DOM listener');
  assert.equal(await c.executeJavaScript('getComputedStyle(document.querySelector("h1")).color'),'rgb(12, 34, 56)','CSS applied');
  assert.equal(await c.executeJavaScript('typeof page'),'undefined','no hook API exposed to website');
  const logCount=state.logs.length;
  require('electron').ipcMain.emit('site-developer-event',{sender:c,senderFrame:c.mainFrame},{token:'invalid',kind:'control',value:'reload'});
  assert.equal(api.developerState(c,origin).logs.length,logCount,'rejects forged hook tokens');
  api.clearDeveloperLogs(c,origin);
  assert.equal(api.developerState(c,origin).logs.length,0);
  api.updateSiteSettings('work',origin,{developer:{...config,before:'',after:"throw new Error('Intentional fixture error');"}});
  await c.loadURL(origin+'/error');
  await until(()=>api.developerState(c,origin).status==='error');
  assert(api.developerState(c,origin).logs.some(l=>l.level==='error'&&l.message.includes('Intentional fixture error')));
  api.updateSiteSettings('work',origin,{developer:{...config,before:'',after:"page.reload();"}});
  api.resetDeveloperState(c,origin);
  await c.loadURL(origin+'/loop').catch(error=>{if(error.code!=='ERR_ABORTED')throw error;});
  await until(()=>api.developerState(c,origin).logs.some(l=>l.message.includes('control loop paused')));
  assert.equal(api.developerState(c,origin).status,'error');
  api.updateSiteSettings('work',origin,{developer:{...config,enabled:false}});
  api.resetDeveloperState(c,origin);
  await c.loadURL(origin+'/off');
  await wait(100);
  assert.equal(api.developerState(c,origin).logs.length,0,'disabled hooks never run');
  assert.equal(await c.executeJavaScript('document.documentElement.dataset.beforeObserved'),'missing');
  assert(!api.getSiteSettings('personal',origin).developer,'profile isolation');
  assert(!api.getSiteSettings('work','https://example.com').developer,'origin isolation');
  console.log('Native lifecycle, async API, CSS, URL/HTML, isolation, error, page controls, loop guard, clear logs, and disabling passed');
  w.destroy();server.close();app.quit();
}).catch(error=>{console.error(error);server.close();app.exit(1)});
